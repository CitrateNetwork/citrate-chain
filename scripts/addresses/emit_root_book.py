#!/usr/bin/env python3
"""emit_root_book.py: the live-network address book, contracts/addresses/40204.json.

The live chain is r1006 (block-0 hash in the post-genesis book's `genesisHash`). Its truth is
two books, and this script folds them into the root book every consumer reads:

  * contracts/addresses/r1006/40204.json, the genesis book (scripts/genesis/r1006/emit_book.py;
    citrate-core pins it by sha256, so it is read here and never rewritten);
  * contracts/addresses/r1006/40204.postgenesis.json, the contracts deployed after block 0.

Output layout is the root book's: top-level metadata, then `contracts` (the genesis contracts in
their book order, then the post-genesis contracts in theirs, under the post-genesis keys, for
example `Quorum.AnchorRegistry`), `aaStack`, `genesis`, `precompiles`, the two top-level
membership pins, and `governance`. Addresses are copied exactly as the r1006 books spell them.
`source` names both books with their sha256, so a reader can tell which inputs produced the file.

Fails closed (exit 1, nothing written) when the inputs disagree: a chain id other than 40204,
mismatched chain name / RPC / explorer, a malformed address or genesis hash, an unknown top-level
key (it would be dropped silently), a post-genesis name that redefines a genesis name, an address
listed under two names across contracts / aaStack / genesis / precompiles, or a governance /
top-level pin that is not the same-named (or, for governance, some) `contracts` entry.

  emit_root_book.py            write contracts/addresses/40204.json
  emit_root_book.py --check    exit 1 if the committed file differs from what this would write

Deterministic: no clock, no network; fixed key order; two-space JSON with a trailing LF.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENESIS_BOOK = "contracts/addresses/r1006/40204.json"
POSTGENESIS_BOOK = "contracts/addresses/r1006/40204.postgenesis.json"
OUT = "contracts/addresses/40204.json"
REGENERATOR = "scripts/addresses/emit_root_book.py"
CHAIN_ID = 40204

ADDR = re.compile(r"^0x[0-9a-fA-F]{40}$")
HASH32 = re.compile(r"^0x[0-9a-f]{64}$")
SECTIONS = ("contracts", "aaStack", "genesis", "precompiles")
PINS = ("CitrateMemberSBT", "MembershipStakeVault")
GENESIS_KEYS = {"$schema", "chainId", "chainName", "rpcUrl", "explorerUrl", "deployer", "deployedAt",
                "regenerator", "comment", *SECTIONS, *PINS, "governance"}
POSTGENESIS_KEYS = {"chainId", "chainName", "rpcUrl", "explorerUrl", "deployer", "deployedAt", "comment",
                    "genesisHash", "contracts"}
COMMENT = (
    "Canonical contract-address table for the live chain 40204 network, r1006 (block-0 hash in "
    "genesisHash). Generated by scripts/addresses/emit_root_book.py from the r1006 genesis book "
    "(contracts present in block 0) and the r1006 post-genesis book (contracts deployed after block 0, "
    "folded into `contracts` under their own keys); never edit by hand. `deployer` and `deployedAt` "
    "describe the genesis ceremony; `source.postGenesis` names the post-genesis deployer. The r1005 "
    "book is archived in contracts/addresses/r1005/. See contracts/addresses/README.md."
)


class BookError(Exception):
    pass


def _addr(where: str, v: object) -> str:
    if not isinstance(v, str) or not ADDR.match(v):
        raise BookError(f"{where}: not a 20-byte hex address: {v!r}")
    return v


def _section(book: dict, name: str, where: str) -> dict:
    sec = book.get(name, {})
    if not isinstance(sec, dict):
        raise BookError(f"{where}.{name} is not an object")
    for k, v in sec.items():
        _addr(f"{where}.{name}.{k}", v)
    return sec


def build(genesis: dict, post: dict, genesis_sha: str, post_sha: str) -> dict:
    for where, book, allowed in (("genesis book", genesis, GENESIS_KEYS), ("post-genesis book", post, POSTGENESIS_KEYS)):
        unknown = sorted(set(book) - allowed)
        if unknown:
            raise BookError(f"{where} has keys this generator does not carry: {unknown}")
        if book.get("chainId") != CHAIN_ID:
            raise BookError(f"{where} chainId is {book.get('chainId')!r}, not {CHAIN_ID}")
        _addr(f"{where}.deployer", book.get("deployer"))
    for k in ("chainName", "rpcUrl", "explorerUrl"):
        if genesis.get(k) != post.get(k):
            raise BookError(f"{k} differs: genesis book {genesis.get(k)!r}, post-genesis book {post.get(k)!r}")
    genesis_hash = post.get("genesisHash")
    if not isinstance(genesis_hash, str) or not HASH32.match(genesis_hash):
        raise BookError(f"post-genesis book genesisHash is not a 32-byte lowercase hex hash: {genesis_hash!r}")

    g = {s: _section(genesis, s, "genesis book") for s in SECTIONS}
    pg = _section(post, "contracts", "post-genesis book")
    for k in set(post) - {"contracts"}:
        if isinstance(post[k], dict):
            raise BookError(f"post-genesis book section {k!r} is not carried")

    # Every name the genesis book defines, in any section or as a top-level pin.
    genesis_names = {n for s in SECTIONS for n in g[s]} | set(genesis.get("governance", {})) | set(PINS)
    shadow = sorted(set(pg) & genesis_names)
    if shadow:
        raise BookError(f"post-genesis names redefine genesis names: {shadow}")

    contracts = dict(g["contracts"])
    contracts.update(pg)
    out_sections = {"contracts": contracts, "aaStack": g["aaStack"], "genesis": g["genesis"],
                    "precompiles": g["precompiles"]}

    names: dict[str, str] = {}
    owners: dict[str, str] = {}
    for s, sec in out_sections.items():
        for n, a in sec.items():
            if n in names:
                raise BookError(f"name {n} is in both {names[n]} and {s}")
            names[n] = s
            al = a.lower()
            if al in owners:
                raise BookError(f"address {a} is listed as both {owners[al]} and {s}.{n}")
            owners[al] = f"{s}.{n}"

    pins = {}
    for p in PINS:
        v = _addr(f"genesis book.{p}", genesis.get(p))
        if contracts.get(p, "").lower() != v.lower():
            raise BookError(f"top-level {p} {v} is not contracts.{p} {contracts.get(p)}")
        pins[p] = v

    gov = genesis.get("governance")
    if not isinstance(gov, dict) or set(gov) != {"GOVERNANCE", "GUARDIAN"}:
        raise BookError(f"genesis book governance must hold exactly GOVERNANCE and GUARDIAN: {gov!r}")
    for k, v in gov.items():
        _addr(f"genesis book.governance.{k}", v)
        if not owners.get(v.lower(), "").startswith("contracts."):
            raise BookError(f"governance.{k} {v} is not a contracts entry")

    return {
        "$schema": "./schema.json",
        "chainId": CHAIN_ID,
        "chainName": genesis["chainName"],
        "rpcUrl": genesis["rpcUrl"],
        "explorerUrl": genesis["explorerUrl"],
        "genesisHash": genesis_hash,
        "deployer": genesis["deployer"],
        "deployedAt": genesis["deployedAt"],
        "regenerator": REGENERATOR,
        "source": {
            "genesis": {
                "path": GENESIS_BOOK,
                "sha256": genesis_sha,
                "regenerator": genesis.get("regenerator"),
                "deployer": genesis["deployer"],
                "deployedAt": genesis["deployedAt"],
                "contracts": len(g["contracts"]),
            },
            "postGenesis": {
                "path": POSTGENESIS_BOOK,
                "sha256": post_sha,
                "deployer": post["deployer"],
                "deployedAt": post["deployedAt"],
                "contracts": len(pg),
            },
        },
        "comment": COMMENT,
        **out_sections,
        **pins,
        "governance": {"GOVERNANCE": gov["GOVERNANCE"], "GUARDIAN": gov["GUARDIAN"]},
    }


def render(root: Path = ROOT) -> str:
    gb = (root / GENESIS_BOOK).read_bytes()
    pb = (root / POSTGENESIS_BOOK).read_bytes()
    book = build(json.loads(gb), json.loads(pb), hashlib.sha256(gb).hexdigest(), hashlib.sha256(pb).hexdigest())
    return json.dumps(book, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the committed root book is stale")
    ap.add_argument("--root", default=str(ROOT), help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    root = Path(args.root)
    try:
        text = render(root)
    except (BookError, OSError, ValueError) as e:
        print(f"emit_root_book: {e}", file=sys.stderr)
        return 1
    out = root / OUT
    if args.check:
        current = out.read_text() if out.exists() else ""
        if current != text:
            print(f"emit_root_book: {OUT} is stale; run {REGENERATOR} and commit the result", file=sys.stderr)
            return 1
        print(f"emit_root_book: {OUT} matches the r1006 books")
        return 0
    out.write_text(text)
    print(f"emit_root_book: wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
