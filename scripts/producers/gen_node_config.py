#!/usr/bin/env python3
"""Generate a producer node's config for a network profile.

Writes three files into --out-dir (default /etc/citrate):

  node.toml            the node config (schema: node/src/config.rs, deny_unknown_fields)
  citrate-node.env     consensus environment every node on the network must share
  citrate-node.service systemd unit running the release binary as the `citrate` user

The coinbase is the operator's STAKER address. Consensus requires a block's coinbase to
equal the registered staker of its proposer (core/execution/src/executor.rs, check 3c),
so a producer whose coinbase differs from the address that called registerValidator has
every block rejected.

Mining defaults to OFF: the node first joins as a follower, mints its proposer.key and
syncs. Turn mining on (--mining on) only once verify_producer.py reports the validator
active. Nothing here reads or writes keys.

  python3 gen_node_config.py --profile 40204-r1005 --staker 0xYourStakerAddress
  python3 gen_node_config.py --profile 40204-r1005 --staker 0x... --mining on --force
  python3 gen_node_config.py --profile rehearsal-1 --staker 0x... --dry-run
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import producerlib as pl  # noqa: E402

DEFAULT_OUT = "/etc/citrate"
DEFAULT_DATA = "/var/lib/citrate/data"
DEFAULT_BIN = "/usr/local/bin/citrate-node"


def toml_str(s: str) -> str:
    return json.dumps(s)  # a JSON string literal is a valid TOML basic string


def render_node_toml(prof: pl.Profile, staker: str, data_dir: str, p2p_port: int, mining: bool) -> str:
    cp = prof["checkpoint"]
    boot = ",\n".join(f"    {toml_str(b)}" for b in prof["bootstrap_nodes"])
    gp = prof.raw.get("genesis_profile")
    lines = [
        f"# Citrate producer node config, profile {prof.name}.",
        "# Generated by scripts/producers/gen_node_config.py. Regenerate instead of editing.",
        "# Schema: node/src/config.rs (unknown keys are rejected at start-up).",
        "",
        "[chain]",
        f"chain_id = {int(prof['chain_id'])}",
        'genesis_hash = ""',
        f"block_time = {int(prof['block_time'])}",
        f"ghostdag_k = {int(prof['ghostdag_k'])}",
    ]
    if gp:
        lines.append(f"genesis_profile = {toml_str(gp)}")
    lines += [
        "",
        "[network]",
        f'listen_addr = "0.0.0.0:{p2p_port}"',
        "bootstrap_nodes = [",
        boot,
        "]",
        "max_peers = 50",
        "allowed_peers = []",
        "",
        "[rpc]",
        "# Local only. Monitoring and the watchdog read it on the host; nothing public.",
        "enabled = true",
        'listen_addr = "127.0.0.1:8545"',
        'ws_addr = "127.0.0.1:8546"',
        "allow_eth_send_transaction = false",
        "",
        "[storage]",
        f"data_dir = {toml_str(data_dir)}",
        "pruning = false",
        "keep_blocks = 100000",
        "",
        "[mining]",
        f"enabled = {'true' if mining else 'false'}",
        "# The staker address that registered this node (consensus: coinbase == staker).",
        f"coinbase = {toml_str(staker[2:])}",
        f"target_block_time = {int(prof['block_time'])}",
        f"min_gas_price = {int(prof.raw.get('gas_price_wei', 1_000_000_000))}",
        "",
        "[vrf]",
        "strict_vrf = true",
        "migration_mode = false",
        "",
        "[checkpoint]",
        f"interval = {int(cp['interval'])}",
        f"committee_size = {int(cp['committee_size'])}",
        f"quorum_threshold = {int(cp['quorum_threshold'])}",
        "",
    ]
    return "\n".join(lines)


def render_env(prof: pl.Profile) -> str:
    env = {
        "CITRATE_VALIDATOR_REGISTRY": prof["validator_registry"],
        "CITRATE_VALIDATOR_ACTIVATION_HEIGHT": str(prof["validator_activation_height"]),
    }
    for k, v in prof["env"].items():
        if not k.startswith("CITRATE_") or not str(v).replace("_", "").isalnum():
            raise pl.ToolError(f"profile env {k}={v!r} is not a plain CITRATE_* value")
        env[k] = str(v)
    out = [
        f"# Consensus environment for profile {prof.name}. Every node on this network must",
        "# carry identical values, or admission verdicts diverge (a fork). Do not edit by hand.",
    ]
    out += [f"{k}={v}" for k, v in sorted(env.items())]
    out += [
        "",
        "# Operational (not consensus): Prometheus metrics on loopback only (127.0.0.1:9090).",
        "CITRATE_METRICS=1",
    ]
    return "\n".join(out) + "\n"


def render_unit(out_dir: str, data_dir: str, binary: str) -> str:
    protect_home = "true" if not data_dir.startswith("/home/") else "read-only"
    return f"""[Unit]
Description=Citrate node (producer)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=citrate
Group=citrate
EnvironmentFile={out_dir}/citrate-node.env
ExecStart={binary} --config {out_dir}/node.toml
Restart=always
RestartSec=5s
LimitNOFILE=65536
# Memory backstop sized for an 8 GB host: throttle reclaim at 6 GiB, kill at
# 6.5 GiB (Restart=always brings the node back), and bound swap so a growing
# node is restarted instead of thrashing the box.
MemoryHigh=6G
MemoryMax=6656M
MemorySwapMax=1G
# Two glibc malloc arenas: with the default (8 per core) the node's RSS kept
# creeping under sustained load from arena fragmentation; capped, it is flat.
Environment=MALLOC_ARENA_MAX=2
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome={protect_home}
ReadWritePaths={data_dir}
UMask=0077

[Install]
WantedBy=multi-user.target
"""


def render_all(args: argparse.Namespace, prof: pl.Profile) -> dict[str, str]:
    staker = pl.norm_addr(args.staker)
    if not args.data_dir.startswith("/"):
        raise pl.ToolError("--data-dir must be absolute")
    if not (1024 <= args.p2p_port <= 65535):
        raise pl.ToolError("--p2p-port must be 1024-65535")
    return {
        "node.toml": render_node_toml(prof, staker, args.data_dir, args.p2p_port, args.mining == "on"),
        "citrate-node.env": render_env(prof),
        "citrate-node.service": render_unit(args.out_dir, args.data_dir, args.binary),
    }


def write_atomic(path: Path, content: str, mode: int) -> None:
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(content)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profile", required=True, help="profile name in profiles/ or a path")
    ap.add_argument("--staker", required=True, help="your staker address (becomes [mining] coinbase)")
    ap.add_argument("--out-dir", default=DEFAULT_OUT)
    ap.add_argument("--data-dir", default=DEFAULT_DATA)
    ap.add_argument("--binary", default=DEFAULT_BIN)
    ap.add_argument("--p2p-port", type=int, default=30303)
    ap.add_argument("--mining", choices=["off", "on"], default="off")
    ap.add_argument("--force", action="store_true", help="replace existing files")
    ap.add_argument("--dry-run", action="store_true", help="print the files; write nothing")
    args = ap.parse_args(argv)
    try:
        prof = pl.load_profile(args.profile, allow_pending=args.dry_run)
        files = render_all(args, prof)
        if args.dry_run:
            if prof["status"] != "ready":
                print(f"# DRY RUN: profile {prof.name} is {prof['status']!r}; these files are NOT usable.")
            for name, content in files.items():
                print(f"# ===== {args.out_dir}/{name} =====")
                print(content)
            return 0
        out = Path(args.out_dir)
        if not out.is_dir():
            raise pl.ToolError(f"{out} does not exist (create it as root, mode 0755)")
        existing = [n for n in files if (out / n).exists()]
        if existing and not args.force:
            raise pl.ToolError(f"{', '.join(existing)} already exist in {out}; pass --force to replace")
        modes = {"node.toml": 0o644, "citrate-node.env": 0o644, "citrate-node.service": 0o644}
        for name, content in files.items():
            write_atomic(out / name, content, modes[name])
            print(f"wrote {out / name}")
        print(f"mining = {args.mining}. Next: install the unit (see docs/ops/PRODUCER_OPERATOR_RUNBOOK.md §5).")
        return 0
    except pl.ToolError as e:
        print(f"gen_node_config: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
