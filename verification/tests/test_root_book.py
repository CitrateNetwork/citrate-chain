"""The root address book (contracts/addresses/40204.json) is the live r1006 network's book.

It is generated by scripts/addresses/emit_root_book.py from the two r1006 books (the genesis book,
which citrate-core pins by sha256, and the post-genesis book). These tests fail when the committed
root drifts from the generator, when a name or address collides, when the root stops naming the
r1006 genesis, or when the generator accepts inputs it should refuse. The r1005 book stays in
contracts/addresses/r1005/ as history.
"""
import copy
import hashlib
import importlib.util
import json
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ADDRS = ROOT / "contracts" / "addresses"
R1006_GENESIS = "0xa3651a272fe411948cbb4cf7cca4cee44be4248d32ab4376cea7636821c6cdd4"
R1005_STATE_ROOT = "0x1dcfc4909dd9fdcb0f03c823d627e4b2032cc86bef5fc4561030d6c64b9775f1"
ADDR = re.compile(r"^0x[0-9a-fA-F]{40}$")
SECTIONS = ("contracts", "aaStack", "genesis", "precompiles")

_spec = importlib.util.spec_from_file_location("emit_root_book", ROOT / "scripts" / "addresses" / "emit_root_book.py")
erb = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(erb)


def load(rel):
    return json.loads((ADDRS / rel).read_text())


class RootBookIsGenerated(unittest.TestCase):
    def test_committed_root_equals_generator_output(self):
        self.assertEqual((ADDRS / "40204.json").read_text(), erb.render(ROOT),
                         "contracts/addresses/40204.json is stale: run scripts/addresses/emit_root_book.py")

    def test_check_mode_passes_on_the_committed_root(self):
        self.assertEqual(erb.main(["--check"]), 0)

    def test_source_hashes_name_the_committed_r1006_books(self):
        src = load("40204.json")["source"]
        for key, rel in (("genesis", "r1006/40204.json"), ("postGenesis", "r1006/40204.postgenesis.json")):
            self.assertEqual(src[key]["path"], f"contracts/addresses/{rel}")
            self.assertEqual(src[key]["sha256"], hashlib.sha256((ADDRS / rel).read_bytes()).hexdigest())


class RootBookContent(unittest.TestCase):
    def setUp(self):
        self.root = load("40204.json")
        self.genesis = load("r1006/40204.json")
        self.post = load("r1006/40204.postgenesis.json")

    def test_names_the_live_r1006_network(self):
        self.assertEqual(self.root["chainId"], 40204)
        self.assertEqual(self.root["genesisHash"], R1006_GENESIS)
        self.assertEqual(self.root["deployer"], self.genesis["deployer"])
        self.assertEqual(self.root["regenerator"], "scripts/addresses/emit_root_book.py")

    def test_layout_is_the_root_books(self):
        self.assertEqual(list(self.root), [
            "$schema", "chainId", "chainName", "rpcUrl", "explorerUrl", "genesisHash", "deployer", "deployedAt",
            "regenerator", "source", "comment", "contracts", "aaStack", "genesis", "precompiles",
            "CitrateMemberSBT", "MembershipStakeVault", "governance"])

    def test_every_r1006_entry_is_carried_unchanged(self):
        for s in SECTIONS:
            for n, a in self.genesis[s].items():
                self.assertEqual(self.root[s].get(n), a, f"{s}.{n}")
        for n, a in self.post["contracts"].items():
            self.assertEqual(self.root["contracts"].get(n), a, f"post-genesis {n}")
        self.assertEqual(len(self.root["contracts"]), len(self.genesis["contracts"]) + len(self.post["contracts"]))
        for s in ("aaStack", "genesis", "precompiles"):
            self.assertEqual(self.root[s], self.genesis[s])
        self.assertEqual(self.root["governance"], self.genesis["governance"])
        self.assertIn("Quorum.AnchorRegistry", self.root["contracts"])

    def test_no_name_collides_across_sections(self):
        seen = {}
        for s in SECTIONS:
            for n in self.root[s]:
                self.assertNotIn(n, seen, f"{n} is in {seen.get(n)} and {s}")
                seen[n] = s

    def test_no_address_is_listed_under_two_names(self):
        seen = {}
        for s in SECTIONS:
            for n, a in self.root[s].items():
                self.assertRegex(a, ADDR, f"{s}.{n}")
                self.assertNotIn(a.lower(), seen, f"{a} is {seen.get(a.lower())} and {s}.{n}")
                seen[a.lower()] = f"{s}.{n}"
        # The top-level pins and governance alias contracts entries; they add no new address.
        for p in ("CitrateMemberSBT", "MembershipStakeVault"):
            self.assertEqual(self.root[p], self.root["contracts"][p])
        self.assertEqual(self.root["governance"]["GOVERNANCE"], self.root["contracts"]["GovernanceTimelock"])
        self.assertEqual(self.root["governance"]["GUARDIAN"], self.root["contracts"]["GuardianTimelock"])

    def test_r1005_only_governance_fields_are_not_carried(self):
        # r1005's GOVERNANCE/GUARDIAN were 2-of-3 MultisigTimelock2of3 with a 7200 s delay; r1006's are
        # OZ TimelockControllers fronted by MultisigProposers (3-of-5, 172800 s / 2-of-3, 3600 s on chain).
        self.assertEqual(set(self.root["governance"]), {"GOVERNANCE", "GUARDIAN"})

    def test_top_level_keys_are_in_the_schema(self):
        schema = load("schema.json")
        self.assertEqual(sorted(set(self.root) - set(schema["properties"])), [])
        self.assertEqual([k for k in schema["required"] if k not in self.root], [])


class GeneratorRefuses(unittest.TestCase):
    def setUp(self):
        self.g = load("r1006/40204.json")
        self.p = load("r1006/40204.postgenesis.json")

    def refuses(self, g, p, needle):
        with self.assertRaises(erb.BookError) as cm:
            erb.build(g, p, "0" * 64, "0" * 64)
        self.assertIn(needle, str(cm.exception))

    def test_a_post_genesis_name_that_shadows_a_genesis_name(self):
        p = copy.deepcopy(self.p)
        p["contracts"]["AnchorRegistry"] = "0x" + "11" * 20
        self.refuses(self.g, p, "redefine genesis names")

    def test_an_address_under_two_names(self):
        p = copy.deepcopy(self.p)
        p["contracts"]["Duplicate"] = self.g["contracts"]["ModelRegistry"]
        self.refuses(self.g, p, "is listed as both")

    def test_another_chain(self):
        p = copy.deepcopy(self.p)
        p["chainId"] = 1
        self.refuses(self.g, p, "chainId")

    def test_a_malformed_genesis_hash(self):
        p = copy.deepcopy(self.p)
        p["genesisHash"] = "0x1234"
        self.refuses(self.g, p, "genesisHash")

    def test_a_malformed_address(self):
        p = copy.deepcopy(self.p)
        p["contracts"]["AppRegistry"] = "0x1234"
        self.refuses(self.g, p, "not a 20-byte hex address")

    def test_an_unknown_top_level_key(self):
        g = copy.deepcopy(self.g)
        g["planned"] = {}
        self.refuses(g, self.p, "does not carry")

    def test_a_top_level_pin_that_disagrees_with_contracts(self):
        g = copy.deepcopy(self.g)
        g["CitrateMemberSBT"] = "0x" + "22" * 20
        self.refuses(g, self.p, "top-level CitrateMemberSBT")

    def test_governance_outside_contracts(self):
        g = copy.deepcopy(self.g)
        g["governance"]["GUARDIAN"] = "0x" + "33" * 20
        self.refuses(g, self.p, "governance.GUARDIAN")


class AddressCodeGenesisGate(unittest.TestCase):
    """check_address_code.py ties the getCode snapshot to the book's block 0 (no network here)."""

    def setUp(self):
        import sys
        sys.path.insert(0, str(ROOT / "verification"))
        import check_address_code
        self.cac = check_address_code
        self.book = load("40204.json")
        self.snap = json.loads((ROOT / "verification" / "address-code.snapshot.json").read_text())

    def test_committed_snapshot_was_probed_on_the_books_block_0(self):
        self.assertEqual(self.snap["genesisHash"], self.book["genesisHash"])
        self.assertEqual(self.cac.check_claims(self.book, self.snap), [])

    def test_a_snapshot_from_another_network_fails_offline(self):
        snap = dict(self.snap, genesisHash="0x" + "ab" * 32)
        errs = self.cac.check_claims(self.book, snap)
        self.assertTrue(any("re-run with --probe on the book's network" in e for e in errs), errs)

    def test_probe_refuses_an_rpc_on_another_block_0(self):
        answers = {"eth_chainId": hex(40204), "eth_getBlockByNumber": {"hash": "0x" + "cd" * 32}}
        orig = self.cac.rpc
        self.cac.rpc = lambda url, method, params: answers[method]
        try:
            with self.assertRaises(SystemExit) as cm:
                self.cac.probe("http://127.0.0.1:9", self.book)
        finally:
            self.cac.rpc = orig
        self.assertIn("block-0 hash", str(cm.exception))


class R1005Archive(unittest.TestCase):
    def test_archive_is_the_r1005_book_and_ledger(self):
        book = load("r1005/40204.json")
        ledger = load("r1005/40204.provenance.json")
        self.assertEqual(book["$schema"], "../schema.json")
        self.assertTrue(book["regenerator"].startswith("contracts/addresses/r1005/40204.provenance.json"))
        self.assertEqual(ledger["genesisStateRoot"], R1005_STATE_ROOT)
        self.assertEqual(book["deployer"].lower(), ledger["deployer"].lower())
        self.assertNotIn("genesisHash", book)

    def test_nothing_r1005_is_left_at_the_root(self):
        for name in ("40204.provenance.json", "dpf-40204.json", "dpf-40204.env", "dpf-40204.checksummed.txt"):
            self.assertFalse((ADDRS / name).exists(), f"{name} belongs in contracts/addresses/r1005/")


